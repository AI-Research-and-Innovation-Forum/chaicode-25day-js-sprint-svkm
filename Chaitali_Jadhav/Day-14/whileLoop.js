// while loop

let i = 1
while (i <= 10) {
    console.log(`Value of index is ${i}`);
    i = i+2
}

let myArray = ['flash' , 'batman' , 'superman']

let arr = 0
while(arr < myArray.length){
    console.log(`Value is ${myArray[arr]}`);
    arr++
    
}


// do-While loop
// execute at least one time, then check condition.

let score = 11
do {
    console.log(`Score is ${score}`);
    score++
} while (score <= 10);